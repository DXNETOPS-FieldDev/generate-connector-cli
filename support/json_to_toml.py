#!/usr/bin/env python3
"""
json_to_toml.py — Convert an AppNeta alarm connector JSON to a TOML config.

Accepts any AppNeta v4 connector alarm JSON — whether fetched via API,
exported from the UI, or written as a pre-update backup by generate_connector.py
— and produces a TOML file compatible with generate_connector.py.

Common uses:
  - Seed a TOML from an existing connector (export once, version-control it)
  - Recover a connector config from a backup written before a bad PUT
  - Convert a connector shared as JSON into the team's standard TOML format

Usage:
  python support/json_to_toml.py CONNECTOR.json
  python support/json_to_toml.py CONNECTOR.json -o output.toml
  python support/json_to_toml.py CONNECTOR.json --stdout

Masked credential values (***...) are detected and the script exits with
an error listing every field that must be filled in before conversion.

ID-based filters (monitoringPointId, monitoringPolicyId, etc.) cannot be
reverse-resolved to names without an API call. They are emitted as TOML
comments with the raw IDs listed; replace each with the corresponding
monitoring_point_names / monitoring_policy_names entry.
"""
import argparse
import json
import re
import sys
from pathlib import Path


_MASKED = re.compile(r"^\*+$")


# ---------------------------------------------------------------------------
# Masked value detection
# ---------------------------------------------------------------------------

def scan_masked(obj: object, path: str = "") -> list[str]:
    """Return a list of dotted-path strings for every masked (***) value."""
    found: list[str] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            found.extend(scan_masked(v, f"{path}.{k}" if path else k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found.extend(scan_masked(v, f"{path}[{i}]"))
    elif isinstance(obj, str) and _MASKED.match(obj):
        found.append(path)
    return found


# ---------------------------------------------------------------------------
# TOML serialization helpers
# ---------------------------------------------------------------------------

def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _filter_block(lines: list[str], section: str, block: dict) -> None:
    """Append a [include] or [exclude] TOML block from an API response dict."""
    has_content = False
    section_lines: list[str] = [f"[{section}]"]

    # Glob/name strings — round-trip cleanly
    names = block.get("monitoringPointName", [])
    if names:
        vals = ", ".join(_toml_str(n) for n in names)
        section_lines.append(f"monitoring_point_names        = [{vals}]")
        has_content = True

    # Type strings — round-trip cleanly
    types = block.get("monitoringPointType", [])
    if types:
        vals = ", ".join(_toml_str(t) for t in types)
        section_lines.append(f"monitoring_point_types        = [{vals}]")
        has_content = True

    # Resolved IDs — cannot reverse without API; emit as comments
    mp_ids = block.get("monitoringPointId", [])
    if mp_ids:
        section_lines.append(
            f"# monitoring_point_names = [...]"
            f"  # replace with names for monitoring point IDs: {mp_ids}"
        )
        has_content = True

    policy_ids = block.get("monitoringPolicyId", [])
    if policy_ids:
        section_lines.append(
            f"# monitoring_policy_names = [...]"
            f"  # replace with names for policy IDs: {policy_ids}"
        )
        has_content = True

    group_ids = block.get("monitoringPolicyGroupId", [])
    if group_ids:
        section_lines.append(
            f"# monitoring_policy_group_names = [...]"
            f"  # replace with names for policy group IDs: {group_ids}"
        )
        has_content = True

    section_lines.append("")

    # Tags — exact category/value pairs, round-trip cleanly
    for tag in block.get("tags", []):
        cat = tag.get("category", "")
        val = tag.get("value", "")
        if cat and val:
            section_lines.append(f"[[{section}.tags]]")
            section_lines.append(f"category = {_toml_str(cat)}")
            section_lines.append(f"value    = {_toml_str(val)}")
            section_lines.append("")
            has_content = True

    if has_content:
        lines.extend(section_lines)


# ---------------------------------------------------------------------------
# Main conversion
# ---------------------------------------------------------------------------

def json_to_toml(data: dict) -> str:
    """Convert a connector API response dict to a TOML config string."""
    lines: list[str] = [
        "# Generated by support/json_to_toml.py from a connector backup JSON.",
        "# Review carefully before use:",
        "#   - ID-based filters are emitted as comments — replace with names.",
        "#   - Masked credential values (******) must be restored before use.",
        "#   - base_url is not stored in connector JSON — fill it in below.",
        "",
        '# base_url = "https://your-appneta-instance.pm.appneta.com"',
        "",
    ]

    notify_on = data.get("notifyOn", ["ALARM_RAISED", "ALARM_CLEARED"])
    lines.append(f"notify_on = [{', '.join(_toml_str(n) for n in notify_on)}]")
    lines.append("")

    lines.append("[connector]")
    if data.get("id"):
        lines.append(f"id          = {data['id']}")
    lines.append(f"name        = {_toml_str(data.get('name', ''))}")
    if data.get("description"):
        lines.append(f"description = {_toml_str(data['description'])}")
    lines.append(f"enabled     = {'true' if data.get('enabled', True) else 'false'}")
    lines.append("")

    connectors = data.get("connectors", [])
    conn = connectors[0] if connectors else {}

    lines.append("[webhook]")
    lines.append(f"url               = {_toml_str(conn.get('url', ''))}")
    lines.append(f"method            = {_toml_str(conn.get('method', 'POST'))}")
    lines.append(f"ignore_ssl_errors = {'true' if conn.get('ignoreSslErrors') else 'false'}")
    lines.append("")

    for h in conn.get("headers", []):
        key = (h.get("key") or h.get("name") or "").strip()
        val = h.get("value", "")
        lines.append("[[webhook.headers]]")
        lines.append(f"key   = {_toml_str(key)}")
        lines.append(f"value = {_toml_str(val)}")
        lines.append("")

    auth = conn.get("auth", {})
    lines.append("[webhook.auth]")
    lines.append(f'type = {_toml_str(auth.get("type", "NONE"))}')
    for cred_field in ("username", "password", "token"):
        if auth.get(cred_field):
            lines.append(f'{cred_field} = {_toml_str(auth[cred_field])}')
    lines.append("")

    for section in ("include", "exclude"):
        block = data.get(section)
        if block:
            _filter_block(lines, section, block)

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Convert an AppNeta alarm connector backup JSON to TOML.",
        epilog=(
            "Input JSON can be a backup written by generate_connector.py in PUT mode, "
            "a connector fetched from the AppNeta API, or any v4 alarm connector JSON. "
            "Fix masked (******) header values before converting."
        ),
    )
    parser.add_argument("input", help="Backup JSON file to convert")
    parser.add_argument(
        "-o", "--output",
        help="Output TOML file (default: same directory and stem as input, .toml extension)",
    )
    parser.add_argument(
        "--stdout", action="store_true",
        help="Print TOML to stdout instead of writing a file",
    )
    args = parser.parse_args()

    try:
        with open(args.input, encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError:
        sys.exit(f"ERROR: File not found: {args.input}")
    except json.JSONDecodeError as e:
        sys.exit(f"ERROR: Invalid JSON in {args.input}: {e}")

    masked = scan_masked(data)
    if masked:
        msg = ["ERROR: Masked credential values found — restore these before converting:"]
        for path in masked:
            msg.append(f"  {path}")
        msg.append("\nReplace each ***... value with the real credential, then re-run.")
        sys.exit("\n".join(msg))

    toml_content = json_to_toml(data)

    if args.stdout:
        print(toml_content, end="")
        return

    if args.output:
        out_path = Path(args.output)
    else:
        out_path = Path(args.input).with_suffix(".toml")

    if out_path.exists():
        print(f"[!] Overwriting existing file: {out_path}", file=sys.stderr)

    out_path.write_text(toml_content, encoding="utf-8")
    print(f"Written: {out_path}", file=sys.stderr)
    print(
        "Note: fill in base_url and any masked credential values before use.",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
